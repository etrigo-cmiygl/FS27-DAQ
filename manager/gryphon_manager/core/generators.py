from __future__ import annotations

import json

from cantools.database import conversion as _conv
from cantools.database.can import Database, Message, Node, Signal

from .config import C_TYPES, FIELD_TYPES, MasterConfig, SignalDef
from .model import fmt_id, parse_int


def _signal(sd: SignalDef, receivers: list[str]) -> Signal:
    return Signal(
        name=sd.dbc_name, start=sd.dbc_start, length=sd.bits,
        byte_order="big_endian" if sd.order == "big" else "little_endian",
        is_signed=sd.signed,
        conversion=_conv.BaseConversion.factory(scale=sd.scale, offset=sd.offset),
        minimum=sd.vmin, maximum=sd.vmax, unit=sd.units or None,
        comment=sd.note or None, receivers=receivers)


def _messages(cfg: MasterConfig, screen_only: bool) -> list[Message]:
    msgs: list[Message] = []
    names = {parse_int(fr["id"]): fr.get("name", f"DAQ_{parse_int(fr['id']):03X}")
             for fr in cfg.data.get("screen_frames", []) or []}
    for (cid, ext), sigs in sorted(cfg.by_id.items()):
        is_screen = (not ext) and cid in names
        if screen_only and not is_screen:
            continue
        if is_screen:
            name, sender, rx = names[cid], "DAQ_PICO", ["DASH"]
        elif 0x14080600 <= cid <= 0x14080608 and ext:
            name, sender, rx = f"FT_Simp_{cid - 0x14080600}", "ECU", ["DAQ_PICO"]
        else:
            name, sender, rx = f"CAN_{cid:X}", "OTHER", ["DAQ_PICO"]
        seen: dict[str, int] = {}
        signals = []
        for sd in sigs:
            sg = _signal(sd, rx)
            if sg.name in seen:
                seen[sg.name] += 1
                sg.name = f"{sg.name}_{seen[sg.name]}"
            else:
                seen[sg.name] = 1
            signals.append(sg)
        msgs.append(Message(frame_id=cid, name=name, length=8, signals=signals,
                            senders=[sender], is_extended_frame=ext,
                            cycle_time=50 if is_screen else None, strict=False))
    return msgs


def build_database(cfg: MasterConfig, screen_only: bool = False) -> Database:
    nodes = [Node("DAQ_PICO"), Node("DASH")] if screen_only else \
        [Node("ECU"), Node("DAQ_PICO"), Node("DASH"), Node("OTHER")]
    return Database(messages=_messages(cfg, screen_only), nodes=nodes, version="", strict=False)


def team_dbc(cfg: MasterConfig) -> str:
    return build_database(cfg).as_dbc_string()


def screen_dbc(cfg: MasterConfig) -> str:
    return build_database(cfg, screen_only=True).as_dbc_string()


def c_header(cfg: MasterConfig) -> str:
    rp = cfg.data.get("radio_packet") or {}
    lines = [
        "// Generated by Gryphon Manager from config/channels.yaml. Don't edit by hand.",
        "#ifndef GRYPHON_CHANNELS_H",
        "#define GRYPHON_CHANNELS_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define GRYPHON_CONFIG_VERSION {cfg.version}",
        f"#define GRYPHON_PACKET_LAYOUT_VERSION {int(rp.get('layout_version', 1))}",
        f"#define GRYPHON_PACKET_MAGIC 0x{cfg.radio_magic:08X}u",
        f"#define GRYPHON_PACKET_SIZE {cfg.radio_size}",
        "",
        "typedef enum {",
        "    GRYPHON_SRC_ECU, GRYPHON_SRC_CAN, GRYPHON_SRC_GPS, GRYPHON_SRC_DAQ, GRYPHON_SRC_DAQ_INPUT",
        "} gryphon_source_t;",
        "",
        "typedef enum { GRYPHON_RADIO_OFF, GRYPHON_RADIO_SLOW, GRYPHON_RADIO_FAST } gryphon_radio_rate_t;",
        "",
        "typedef struct {",
        "    const char* key;",
        "    const char* name;",
        "    const char* units;",
        "    gryphon_source_t source;",
        "    uint32_t can_id;",
        "    uint8_t byte;",
        "    uint8_t bits;",
        "    uint8_t big_endian;",
        "    uint8_t is_signed;",
        "    float scale;",
        "    float offset;",
        "    gryphon_radio_rate_t radio;",
        "    uint8_t on_screen;",
        "} gryphon_channel_t;",
        "",
        "typedef enum {",
    ]
    for ch in cfg.channels:
        lines.append(f"    GRYPHON_CH_{str(ch['key']).upper()},")
    lines += ["    GRYPHON_CH_COUNT", "} gryphon_channel_id_t;", "",
              "static const gryphon_channel_t GRYPHON_CHANNELS[GRYPHON_CH_COUNT] = {"]
    for ch in cfg.channels:
        src = ch.get("source") or {}
        stype = src.get("type", "daq")
        sd = cfg.signal_defs.get(ch["key"])
        cid = sd.can_id if sd else 0
        byte, bits = (sd.byte, sd.bits) if sd else (0, 0)
        big = 1 if sd and sd.order == "big" else 0
        signed = 1 if sd and sd.signed else 0
        lines.append(
            f'    {{"{ch["key"]}", "{ch.get("name", "")}", "{ch.get("units", "") or ""}", '
            f'GRYPHON_SRC_{stype.upper()}, 0x{cid:08X}u, {byte}, {bits}, {big}, {signed}, '
            f'{float(ch.get("scale", 1))!r}f, {float(ch.get("offset", 0))!r}f, '
            f'GRYPHON_RADIO_{str(ch.get("radio", "off")).upper()}, {1 if ch.get("screen") else 0}}},')
    lines += ["};", "", "typedef struct __attribute__((packed)) {", "    uint32_t magic;"]
    for name, channel, ftype in cfg.radio_fields:
        lines.append(f"    {C_TYPES[ftype]} {name};")
    lines += ["} gryphon_telemetry_packet_t;", "",
              f"_Static_assert(sizeof(gryphon_telemetry_packet_t) == {cfg.radio_size}, \"packet size\");", ""]
    for fr in cfg.data.get("screen_frames", []) or []:
        fid = parse_int(fr["id"])
        lines.append(f"#define GRYPHON_FRAME_{fr.get('name', 'F')}_ID 0x{fid:03X}u")
        for sg in fr.get("signals", []) or []:
            lines.append(f"//   bytes {sg['byte']}-{sg['byte'] + sg['bits'] // 8 - 1}: {sg.get('name')} "
                         f"= {sg.get('channel')} / {sg.get('scale', 1)} ({sg.get('units', '')})")
    lines += ["", "#endif", ""]
    return "\n".join(lines)


def signal_list(cfg: MasterConfig) -> str:
    out = {"version": cfg.version, "packet_size": cfg.radio_size, "signals": []}
    for ch in cfg.channels:
        sd = cfg.signal_defs.get(ch["key"])
        out["signals"].append({
            "key": ch["key"], "name": ch.get("name"), "units": ch.get("units", ""),
            "group": ch.get("group", ""), "source": (ch.get("source") or {}).get("type"),
            "can_id": fmt_id(sd.can_id, sd.ext) if sd else None,
            "scale": ch.get("scale", 1), "min": ch.get("min"), "max": ch.get("max"),
            "radio": ch.get("radio", "off"), "screen": bool(ch.get("screen")),
            "note": ch.get("note", ""),
        })
    for key, sd in cfg.signal_defs.items():
        if key.startswith("daq."):
            out["signals"].append({"key": key, "name": sd.name, "units": sd.units, "group": sd.group,
                                   "source": "screen_frame", "can_id": fmt_id(sd.can_id, False),
                                   "scale": sd.scale, "min": sd.vmin, "max": sd.vmax})
    return json.dumps(out, indent=2) + "\n"
